const {chromium}=require('../.local/browser-check/node_modules/playwright');
const {spawn}=require('child_process'),assert=require('assert'),fs=require('fs');
(async()=>{
 const server=spawn('.venv/bin/python',['tests/intent-browser-fixture.py'],{stdio:['ignore','pipe','inherit']});let browser;
 try{
  const url=await new Promise((resolve,reject)=>{server.stdout.once('data',data=>resolve(data.toString().trim()));server.once('exit',code=>reject(Error('Fixture exited '+code)))});
  browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream','--autoplay-policy=no-user-gesture-required']});
  const context=await browser.newContext({permissions:['camera','microphone']});const page=await context.newPage(),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',message=>{if(message.type()==='error')console.log('Browser:',message.text())});
  await page.goto(url);await page.locator('#wearing').fill('synthetic-browser-01');
  await page.locator('#focus').selectOption('snaps');
  console.log('Camera API:',await page.evaluate(()=>({available:!!window.CameraReference,handler:!!document.getElementById('enableCamera').onclick,secure:window.isSecureContext})));
  await page.locator('#role').selectOption('evaluation');
  await page.locator('#enableCamera').click();
  console.log('After enable:',await page.locator('#cameraStatus').textContent());
  try{await page.waitForFunction(()=>window.CameraReference?.ready,{},{timeout:30000})}catch(error){console.log('Camera status:',await page.locator('#cameraStatus').textContent());console.log('Page errors:',errors);throw error}
  await page.locator('#startSession').click();
  await page.locator('#trialPanel').waitFor({state:'visible'});
  await page.locator('#nextTrial').click();
  await page.waitForFunction(()=>document.getElementById('phase').textContent==='review',{},{timeout:10000});
  await page.locator('#confirmTrial').click();
  await page.waitForFunction(()=>document.getElementById('error').textContent.includes('actual snap count'));
  await page.locator('#actualSnaps').fill('0');await page.locator('#performed').check();await page.locator('#actualState').selectOption('mixed');
  await page.locator('#confirmTrial').click();
  await page.waitForFunction(()=>document.getElementById('phase').textContent==='complete');
  await page.locator('[data-failure="false_snap"]').click();
  await page.waitForFunction(()=>document.getElementById('flagStatus').textContent.includes('Saved'));
  await page.locator('#finishSession').click();
  await page.waitForFunction(()=>document.getElementById('saveReport').textContent.startsWith('Saved locally'),{},{timeout:20000});
  const status=await (await page.request.get(url+'/api/status')).json();
  assert(status.recording.complete&&!status.recording.active);
  const directory=status.recording.path,meta=JSON.parse(fs.readFileSync(directory+'/metadata.json'));
  assert(meta.camera_reference.complete);assert.equal(meta.dataset_role,'untouched_guided_count_check');
  const trials=JSON.parse(fs.readFileSync(directory+'/intent-trials.json'));assert.equal(trials[0].reported_count,0);assert.equal(trials[0].participant_confirmed,true);
  const rows=fs.readFileSync(directory+'/streams.jsonl','utf8').trim().split('\n').map(JSON.parse);
  for(const kind of ['emg','band_orientation','band_gyro','camera_observation','failure_flag','trial_confirmation'])assert(rows.some(row=>row.kind===kind),kind);
  assert.equal(errors.length,0,errors.join('\n'));
  await page.locator('#focus').selectOption('intent');
  await page.locator('#startSession').click();await page.locator('#nextTrial').waitFor({state:'visible'});await page.locator('#nextTrial').click();
  await page.waitForFunction(()=>document.getElementById('phase').textContent==='review');
  assert(await page.locator('#actionReport').isHidden());
  await page.locator('#intentLabel').selectOption('non_intended');await page.locator('#performed').check();await page.locator('#confirmTrial').click();
  await page.waitForFunction(()=>document.getElementById('phase').textContent==='complete');
  await page.screenshot({path:'.local/browser-check/intent-lab.png',fullPage:true});
  await page.locator('#finishSession').click();await page.waitForFunction(()=>document.getElementById('saveReport').textContent.startsWith('Saved locally'));
  const gateStatus=await (await page.request.get(url+'/api/status')).json();
  const gateTrials=JSON.parse(fs.readFileSync(gateStatus.recording.path+'/intent-gate-trials.json'));
  assert.equal(gateTrials[0].label,'non_intended');assert.equal(gateTrials[0].reported_count,null);
  await page.locator('#focus').selectOption('live_intent');await page.locator('#startSession').click();
  await page.waitForFunction(()=>document.getElementById('phase').textContent==='live');
  assert.equal(await page.locator('#intentToggle').getAttribute('aria-checked'),'false');
  await page.waitForTimeout(2000);await page.locator('#intentToggle').click();
  await page.waitForFunction(()=>document.getElementById('intentToggle').getAttribute('aria-checked')==='true');
  assert(await page.evaluate(()=>window.CameraReference.ready));
  await page.waitForTimeout(3200);await page.locator('#intentToggle').click();
  await page.waitForFunction(()=>document.getElementById('intentToggle').getAttribute('aria-checked')==='false');
  await page.waitForTimeout(2200);await page.locator('#finishSession').click();
  await page.waitForFunction(()=>document.getElementById('saveReport').textContent.startsWith('Saved locally'));
  const toggleStatus=await (await page.request.get(url+'/api/status')).json();
  const toggleIntervals=JSON.parse(fs.readFileSync(toggleStatus.recording.path+'/intent-gate-intervals.json')).intervals;
  assert(toggleIntervals.some(row=>row.label==='intended'));
  assert(JSON.parse(fs.readFileSync(toggleStatus.recording.path+'/metadata.json')).camera_reference.complete);
  console.log(JSON.stringify({syntheticCapture:directory,camera:true,explicitCountRequired:true,reservedEvaluation:true,liveToggleClipped:true,streams:[...new Set(rows.map(row=>row.kind))],pageErrors:errors}));
 }finally{if(browser)await browser.close();server.kill('SIGINT')}
})().catch(error=>{console.error(error);process.exitCode=1});
